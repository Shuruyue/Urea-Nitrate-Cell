"""Run the 36 automated checks and the 11 calibration metrics: print each row and write outputs/validation_table.json;
with --markdown also write VALIDATION.md. Exit code 1 if any check fails (metrics have no threshold)."""
import json
import os
import sys
import numpy as np
import _path  # noqa: F401
from urea_nitrate_cell.validation import run_all


def _span(idx):
    """[28, 29, ..., 38] -> '28–38'; non-contiguous -> '3, 7, 9'."""
    return f"{idx[0]}–{idx[-1]}" if idx == list(range(idx[0], idx[-1] + 1)) else ", ".join(map(str, idx))


def to_markdown(rows):
    fmt = lambda v: "—" if v is None else (f"{v:.4g}" if isinstance(v, (int, float)) else str(v))
    checks = [r for r in rows if r["kind"] == "check"]
    metric_idx = [i for i, r in enumerate(rows, 1) if r["kind"] == "metric"]
    held_out = [(i, r) for i, r in enumerate(rows, 1) if r["cat"] == "Held-out test"]
    out = ["# Validation results", "",
           f"{sum(r['ok'] for r in checks)} / {len(checks)} checks passed. "
           f"Rows {_span(metric_idx)} are {len(metric_idx)} calibration and held-out metrics, reported without a "
           "pass/fail threshold (see below the table). "
           "Generated by `python scripts/validate.py --markdown`; CI reruns every row on each push and fails on any FAIL.", "",
           "| # | Category | Check | Model | Expected | Tolerance | Result | How it is checked |",
           "|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        note = f"; {r['note']}" if r["note"] else ""
        result = "metric" if r["kind"] == "metric" else ("PASS" if r["ok"] else "**FAIL**")
        out.append(f"| {i} | {r['cat']} | {r['name']} | {fmt(r['value'])} | {fmt(r['expect'])} | {fmt(r['tol'])} | "
                   f"{result} | {r['how']}{note} |")
    out += ["", "## Calibration and held-out metrics", "",
            "The rows marked *metric* compare the model with LSV curves digitized from Q. Yao et al., *Sustainability* "
            "**17**, 3835 (2025), CC BY 4.0: the anode curves of Fig. 11a and the cathode curves of Fig. 3b, read from "
            "the journal's figure files every 10 mV, with a reading error of about ±1 mA cm⁻² and ±1 mV "
            "(`urea_nitrate_cell/yao2025.py`). The S1 parameters are fitted to these same curves, so the calibration "
            "rows show how well the fit reproduces its own data; they are not an independent test and carry no "
            "threshold. RMS values are relative errors (j_model − j_data) / (j_data + 3 mA cm⁻²). Where a metric row "
            "has an Expected value, it is the published value, or the value used in `model.py`, that the number is "
            "compared with."]
    for i, r in held_out:
        out += ["", f"The 50 mM cathode curve (row {i}) is left out of the fit and is the only held-out comparison: "
                    f"the model predicts it with {100 * r['value']:.0f} % RMS error. Most of that error comes from a stretch "
                    "where the published 50 mM curve carries more current than the 100 mM curve, which no model with a "
                    "positive reaction order can follow; away from it the error is close to that of the fitted curves "
                    f"(details in row {i}). No independent full-cell data are available yet to test the absolute cell "
                    "voltage."]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    rows = run_all(verbose=True)
    checks = [r for r in rows if r["kind"] == "check"]
    n_fail = sum(not r["ok"] for r in checks)
    print(f"\n{len(checks)} checks, {n_fail} failed; {len(rows) - len(checks)} metrics reported")
    os.makedirs(_path.OUTPUTS, exist_ok=True)
    with open(os.path.join(_path.OUTPUTS, "validation_table.json"), "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=1,
                  default=lambda o: float(o) if isinstance(o, (np.floating, np.integer)) else str(o))
    if "--markdown" in sys.argv:
        with open(os.path.join(_path.ROOT, "VALIDATION.md"), "w", encoding="utf-8", newline="\n") as f:
            f.write(to_markdown(rows))
        print("wrote VALIDATION.md")
    sys.exit(1 if n_fail else 0)
